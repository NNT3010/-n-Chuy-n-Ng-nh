/// Trả về bộ L–M–S đúng theo giới tính (M/F) và tháng tuổi (0–60)
Map<String, double>? whoLmsLookup(String sex, int months) {
  final g = whoLms[sex];
  if (g == null) return null;

  if (g.containsKey(months)) return g[months];

  // Nếu không khớp tháng, tìm tháng gần nhất phía trước
  int nearest = 0;
  for (final m in g.keys) {
    if (m <= months) nearest = m;
  }
  return g[nearest];
}
